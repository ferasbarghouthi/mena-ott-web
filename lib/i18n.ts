export const DICTS: Record<Locale, Dict> = { ar, en };
export const isLocale = (s: string): s is Locale => (LOCALES as string[]).includes(s);

export function errorText(t: Dict, e: unknown) {
  const code = (e as { code?: ApiErrorCode })?.code;
  return (code && (t.errors as Record<string, string>)[code]) || t.errors.generic;
}
